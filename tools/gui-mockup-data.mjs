// GUI mockup data (GUI-PLAN.md §8 step 1): the real Plan for a save copy, written to gui/mockup-data.js.
//   node tools/gui-mockup-data.mjs "<save copy>" [team to show in full, default Missouri]
// To show every status and panel: a few teams are marked reviewed (one with old moves, so it
// shows RE-CHECK) and the shown team's first un-signed recruit is undone (a real lock and rebuild).
import fs from "node:fs";
import os from "node:os";
import path from "node:path";
import { Session } from "../lib/session.mjs";
import { emptyState, rawPlan, buildPlan, movesOf, listSaves, teamArt } from "../lib/gui-plan.mjs";

const [file, showTeam = "Missouri"] = process.argv.slice(2);
if (!file) throw new Error('Usage: node tools/gui-mockup-data.mjs "<save copy>" [team]');
if (path.resolve(file).split(path.sep).includes("test_saves")) throw new Error("Use a copy, not a file in test_saves/.");

const session = new Session();
const info = await session.open(file);
const state = emptyState();
let plan = buildPlan(session, rawPlan(session, state), state);
const shown = () => plan.teams.find(t => t.name === showTeam);
const undone = shown()?.out.find(r => r.result === "Un-signed");
if (undone) state.keep.add(undone.playerIndex);
plan = buildPlan(session, rawPlan(session, state), state);
const withMoves = plan.teams.filter(t => t.status === "CHANGED" && t.name !== showTeam);
for (const t of withMoves.slice(0, 4)) state.reviewed.set(t.index, movesOf(t));
state.reviewed.set(withMoves[4].index, "[[],[]]");
plan = buildPlan(session, rawPlan(session, state), state);

// Rows only for the team shown in full (the lists use the counts).
for (const t of plan.teams) if (t.name !== showTeam) { t.in = []; t.out = []; t.kept = []; }
// The saves list is real; the home folder is written as %USERPROFILE% (the file is committed).
const home = s => s.split(os.homedir()).join("%USERPROFILE%");
const saves = listSaves().map(s => ({ ...s, path: home(s.path) }));
plan.save.filePath = home(plan.save.filePath);
const opened = {
  path: saves.find(s => /SIGNINGDAY$/.test(s.name))?.path ?? info.filePath, fileName: info.fileName, stage: { id: info.stage.id, label: info.stage.label },
  teams: [...session.d.teams.values()].map(t => ({ index: t.index, name: t.name, short: t.short, colors: t.colors, ...teamArt(t.name, t.record.LongName) }))
    .sort((a, b) => a.name.localeCompare(b.name))
};
const data = { plan, saves, opened, picked: session.userTeam.teamIndex, showTeam: shown()?.index };
fs.writeFileSync("gui/mockup-data.js", `// Generated by tools/gui-mockup-data.mjs from ${info.fileName}.\nexport const data = ${JSON.stringify(data)};\n`);
const t = shown();
console.log(`gui/mockup-data.js: ${plan.teams.length} teams; ${showTeam} in ${t?.counts.in} out ${t?.counts.out} kept ${t?.counts.kept} (undid ${undone?.name}); summary ${JSON.stringify(plan.summary)}`);
